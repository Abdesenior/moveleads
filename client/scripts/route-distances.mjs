// Fetches real driving distances (miles) and times (hours) between all site
// cities from the public OSRM demo server in a single table request, and
// writes src/seo/routeDistances.js. Run when cities change:
//   node scripts/route-distances.mjs
import { writeFile } from 'node:fs/promises';
import { CITIES, COORDS } from '../src/seo/routePages.js';

const keys = Object.keys(CITIES);
const coords = keys.map((k) => `${COORDS[k][1]},${COORDS[k][0]}`).join(';');
const url = `https://router.project-osrm.org/table/v1/driving/${coords}?annotations=distance,duration`;

const res = await fetch(url);
const data = await res.json();
if (data.code !== 'Ok') throw new Error(`OSRM: ${data.code} ${data.message || ''}`);

const out = {};
for (let i = 0; i < keys.length; i++) {
  for (let j = i + 1; j < keys.length; j++) {
    const meters = data.distances[i][j];
    const secs = data.durations[i][j];
    if (meters == null || secs == null) continue;
    const key = [keys[i], keys[j]].sort().join('|');
    out[key] = [Math.round(meters / 1609.344 / 5) * 5, Math.round(secs / 3600)];
  }
}

const body = Object.entries(out).sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  '${k}': [${v[0]}, ${v[1]}],`).join('\n');
await writeFile(
  new URL('../src/seo/routeDistances.js', import.meta.url),
  `// Generated by scripts/route-distances.mjs from OSRM driving data. Do not edit by hand.\n// [driving miles (rounded to 5), driving hours]\nexport const ROUTE_DISTANCES = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} city pairs written`);
