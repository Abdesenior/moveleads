// Fetches the main highways for every route page's city pair from the public
// OSRM demo server (one request per second, per its usage policy) and writes
// src/seo/routeHighways.js. Existing entries are kept, so re-runs only fetch
// new pairs:  node scripts/route-highways.mjs
import { writeFile } from 'node:fs/promises';
import { ROUTE_PAGES, COORDS } from '../src/seo/routePages.js';
import { ROUTE_HIGHWAYS } from '../src/seo/routeHighways.js';

const pairs = new Map();
for (const r of Object.values(ROUTE_PAGES)) {
  const key = [r.fromKey, r.toKey].sort().join('|');
  if (!pairs.has(key)) pairs.set(key, key.split('|'));
}

const out = { ...ROUTE_HIGHWAYS };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fetched = 0;

for (const [key, [a, b]] of pairs) {
  if (out[key] !== undefined) continue;
  const coords = `${COORDS[a][1]},${COORDS[a][0]};${COORDS[b][1]},${COORDS[b][0]}`;
  try {
    const res = await fetch(`https://router.project-osrm.org/route/v1/driving/${coords}?overview=false&steps=true`);
    const data = await res.json();
    const summary = data.code === 'Ok' ? data.routes[0].legs[0].summary : '';
    out[key] = summary.replace(/\b(I|US) (\d+)/g, '$1-$2');
    fetched++;
  } catch (err) {
    console.error(`skip ${key}: ${err.message}`);
  }
  await sleep(1100);
}

const body = Object.entries(out).sort(([x], [y]) => x.localeCompare(y))
  .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
await writeFile(
  new URL('../src/seo/routeHighways.js', import.meta.url),
  `// Generated by scripts/route-highways.mjs from OSRM. Do not edit by hand.\n// Main highways on the driving route for each city pair.\nexport const ROUTE_HIGHWAYS = {\n${body}\n};\n`,
);
console.log(`${fetched} fetched, ${Object.keys(out).length} total`);
